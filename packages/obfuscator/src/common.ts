export function extension(relativePath: string): string {
  const base = relativePath.slice(relativePath.lastIndexOf('/') + 1);
  const dot = base.lastIndexOf('.');
  return dot < 1 ? '' : base.slice(dot + 1).toLowerCase();
}

export function basenameWithoutExtension(relativePath: string): string {
  const base = relativePath.slice(relativePath.lastIndexOf('/') + 1);
  const dot = base.lastIndexOf('.');
  return dot < 1 ? base : base.slice(0, dot);
}

export function isImageFile(relativePath: string): boolean {
  return extension(relativePath) in IMAGE_EXTENSIONS;
}

export function isResourceFile(relativePath: string): boolean {
  return extension(relativePath) in RESOURCE_EXTENSIONS;
}

export function isTextFile(relativePath: string): boolean {
  return extension(relativePath) in TEXT_EXTENSIONS;
}

export function classifyLanguage(relativePath: string): Language | undefined {
  return LANGUAGE_EXTENSIONS[extension(relativePath)];
}

/** Text or code files that can carry path/name references worth rewriting during renames. */
export function isReferenceCarrier(relativePath: string): boolean {
  return isTextFile(relativePath) || classifyLanguage(relativePath) !== undefined;
}

/**
 * Code generated by build tooling (json_serializable, freezed, protobuf, …). Seed-generated
 * renames skip these files so generated serializers keep referencing the original names.
 */
export function isGeneratedCode(relativePath: string): boolean {
  return /(?:^|\/)[^/]*\.(?:g|freezed|pb|grpc)\.dart$/.test(relativePath)
    || /(?:^|\/)[^/]*\.g\.(?:java|kt|kts)$/.test(relativePath);
}

/** Walk owned project files deterministically, skipping generated/ignored paths and symlinks. */
export function walkProject(root: string): WalkResult {
  const files: WalkEntry[] = [];
  let skipped = 0;
  function visit(directory: string, prefix: string): void {
    for (const name of readdirSync(directory).sort()) {
      const absolute = join(directory, name);
      const relativePath = prefix ? `${prefix}/${name}` : name;
      const stat = lstatSync(absolute);
      if (stat.isSymbolicLink()) { skipped += 1; continue; }
      if (stat.isDirectory()) {
        if (name in SKIPPED_DIRECTORIES) { skipped += 1; continue; }
        visit(absolute, relativePath);
      } else if (stat.isFile()) {
        if (name in SKIPPED_FILES) { skipped += 1; continue; }
        files.push({ absolute, relative: relativePath });
      } else {
        skipped += 1;
      }
    }
  }
  const rootStat = lstatSync(root);
  if (!rootStat.isDirectory() || rootStat.isSymbolicLink()) throw new Error(`Project root is not a real directory: ${root}`);
  visit(root, '');
  return { files, skipped };
}

/** Deterministic hash of the joined parts. */
export function deriveHash(...parts: string[]): string {
  return createHash('sha256').update(parts.join('\u0000')).digest('hex');
}

/** Deterministic short identifier token: 'obf' + 8 lowercase alphanumeric chars. */
export function deriveToken(seed: string, ...parts: string[]): string {
  const hash = deriveHash(seed, ...parts);
  let value = '';
  for (let index = 0; index < 8; index += 1) value += '0123456789abcdefghijklmnopqrstuvwxyz'[parseInt(hash.slice(index * 2, index * 2 + 2), 16) % 36]!;
  return `obf${value}`;
}

/** Deterministic 24-char uppercase hex token (Xcode UUID shape). */
export function deriveUuid(seed: string, original: string): string {
  const hash = deriveHash(seed, 'uuid', original);
  const value = hash.slice(0, 24).toUpperCase();
  return value === original ? hash.slice(24, 48).toUpperCase() : value;
}

export function seededRandom(seed: string): () => number {
  const hash = deriveHash(seed);
  let state = (parseInt(hash.slice(0, 8), 16) ^ parseInt(hash.slice(8, 16), 16)) >>> 0 || 0x9e3779b9;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function seededInt(seed: string, salt: string, min: number, max: number): number {
  const random = seededRandom(deriveHash(seed, salt));
  return min + Math.floor(random() * (max - min + 1));
}

export function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * Whole-word replacement. Word characters are ASCII identifier chars; CJK and other scripts
 * match because their neighbors fall outside the class. Returns the replacement count.
 */
export function replaceWholeWords(text: string, words: Readonly<Record<string, string>>): { text: string; count: number } {
  let result = text;
  let count = 0;
  for (const key of Object.keys(words).sort((a, b) => b.length - a.length)) {
    if (!key) continue;
    const pattern = new RegExp(`(?<![A-Za-z0-9_$])${escapeRegExp(key)}(?![A-Za-z0-9_$])`, 'g');
    result = result.replace(pattern, () => { count += 1; return words[key]!; });
  }
  return { text: result, count };
}

export function writeIfChanged(entry: WalkEntry, content: string): boolean {
  const previous = readFileSync(entry.absolute);
  if (previous.equals(Buffer.from(content, 'utf8'))) return false;
  writeFileSync(entry.absolute, content);
  return true;
}
